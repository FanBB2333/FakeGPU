#!/usr/bin/env python3
"""Render the public GPU inventory and website statistics from YAML profiles."""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from fakegpu.profile_catalog import catalog_summary, load_profiles  # noqa: E402

OUTPUT = ROOT / "profiles" / "README.md"
WEBSITE = ROOT / "website" / "index.html"
SEGMENTS = (
    ("consumer", "GeForce / TITAN — 游戏与消费级"),
    ("datacenter", "Tesla / Data center — 数据中心"),
    ("workstation", "Quadro / Professional RTX — 专业绘图"),
    ("embedded", "Embedded — 嵌入式"),
    ("test", "Synthetic — 合成测试"),
)
ARCHITECTURES = ("maxwell", "pascal", "volta", "turing", "ampere", "ada", "hopper", "blackwell")


def _number(value: int | float) -> str:
    return f"{value:g}" if value else "—"


def render() -> str:
    profiles = load_profiles()
    summary = catalog_summary(profiles)
    lines = [
        "# NVIDIA GPU profile catalog / GPU 配置目录",
        "",
        "<!-- Generated by scripts/render_gpu_catalog.py; edit YAML profiles, then regenerate. -->",
        "",
        f"{len(profiles)} selectable configurations across {len(summary['architectures'])} architectures "
        f"and {len(summary['compute_capabilities'])} CUDA compute capabilities. "
        "Counts include distinct memory/form-factor variants and synthetic profiles; they are not counts of unique GPU chips.",
        "",
        "覆盖 Maxwell（GTX 900 时代）至 Blackwell（RTX 50 时代）。按游戏卡、数据中心、专业绘图顺序排列，"
        "桌面与笔记本、不同显存容量、PCIe/SXM 等使用独立 ID。涵盖已核实的公开配置，不把所有厂商超频版、"
        "OEM 定制版或未公开参数的 SKU 宣称为已穷尽。",
        "",
        "## Reading specifications / 参数口径",
        "",
        "- Each linked YAML is used by both Python and the native runtime. It contains memory capacity, SM count, "
        "bus width, clocks, L2 cache, CUDA shared-memory/register/thread limits, power fields, data types, sources, and notes.",
        "- `reference` means public specification or an explicitly documented derivation; it does not mean physical calibration. "
        "`measured` and `synthetic` retain their existing meanings. Catalog support does not imply a matching CUDA toolkit or framework still supports an old GPU.",
        "- `—` and a numeric zero in a reference specification mean unknown/unverified, not a hardware capacity of zero. "
        "`doctor --json` exposes `unavailable_fields`. Timing estimates reject profiles missing SM count, core clock, bus width, or memory clock.",
        "- Memory capacity is expressed in GiB (nominal vendor GB is represented as binary capacity unless notes specify otherwise). "
        "Multi-GPU boards and superchips are represented per CUDA GPU, not by adding memory across devices.",
        "- Memory MHz follows the existing analytical convention: half the effective per-pin data rate, "
        "so bandwidth in bytes/s = bus bits / 8 × memory MHz × 2,000,000. This may be derived from published bandwidth "
        "and is not necessarily the physical DRAM oscillator reported by a monitoring tool. Rounding can slightly change derived bandwidth.",
        "- Core clocks are reference boost/operating clocks where documented. Mobile power and clocks depend on OEM configuration; "
        "the YAML notes identify reference envelopes. Power limit is a public reference ceiling when known, not measured typical consumption. "
        "CUDA shared-memory limits refer to usable shared memory, not the larger combined L1/shared cache.",
        "",
        "## Coverage / 覆盖范围",
        "",
        "| Architecture | Consumer | Data center | Workstation | Other |",
        "|---|---:|---:|---:|---:|",
    ]
    for arch in ARCHITECTURES:
        selected = [p for p in profiles.values() if p.architecture == arch]
        counts = [sum(p.segment == segment for p in selected) for segment in ("consumer", "datacenter", "workstation")]
        other = len(selected) - sum(counts)
        lines.append(f"| {arch.title()} | {counts[0]} | {counts[1]} | {counts[2]} | {other} |")
    lines.extend([
        "",
        "Compute capability sources: [current NVIDIA table](https://developer.nvidia.com/cuda/gpus), "
        "[legacy NVIDIA table](https://developer.nvidia.com/cuda/gpus/legacy). "
        "These tables omit some mobile, regional, and memory variants; per-profile notes and source links supply additional evidence. "
        "The checked-in table snapshot is kept separate from researched profile specifications.",
        "",
        "Research notes: [consumer](../docs/catalog-consumer-research.md), "
        "[data center](../docs/catalog-datacenter-research.md), "
        "[workstation](../docs/catalog-workstation-research.md). "
        "They describe source conflicts, derived parameters, and coverage boundaries.",
        "",
        "```bash",
        "python3 -m fakegpu doctor --list-profiles",
        "python3 -m fakegpu doctor --profile gtx1660-super --json",
        "FAKEGPU_PROFILE=rtx5090 python3 your_script.py",
        "python3 scripts/render_gpu_catalog.py --check",
        "```",
    ])
    for segment, title in SEGMENTS:
        selected = [p for p in profiles.values() if p.segment == segment]
        if not selected:
            continue
        lines.extend(["", f"## {title} ({len(selected)})", ""])
        for arch in ARCHITECTURES:
            rows = [p for p in selected if p.architecture == arch]
            if not rows:
                continue
            lines.extend([
                f"### {arch.title()}", "",
                "| Profile ID / YAML | CC | GiB | SMs | Bus bits | Core MHz | Memory MHz | Limit W | Source |",
                "|---|---:|---:|---:|---:|---:|---:|---:|---|",
            ])
            for p in rows:
                values = (p.memory_bytes / 2**30, p.sm_count, p.memory_bus_width_bits, p.core_clock_mhz,
                          p.memory_clock_mhz, p.max_power_limit_mw / 1000)
                cells = " | ".join(_number(value) for value in values)
                source = f"[spec]({p.spec_source})" if p.spec_source else "—"
                lines.append(f"| [{p.id}]({p.profile_path}) | {p.compute_capability_text} | {cells} | {source} |")
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_website(source: str) -> str:
    """Keep the landing page's accessible catalog statistics in sync."""

    profiles = load_profiles()
    summary = catalog_summary(profiles)
    for attribute, count in (
        ("data-gpu-profile-count", len(profiles)),
        ("data-gpu-capability-count", len(summary["compute_capabilities"])),
    ):
        pattern = rf"(<[^>]+\b{attribute}\b[^>]*>)[^<]*(</[^>]+>)"
        source, replacements = re.subn(
            pattern, lambda match: f"{match[1]}{count}{match[2]}", source
        )
        if not replacements:
            raise ValueError(f"website is missing {attribute} elements")

    samples = {
        "maxwell": "gtx980", "pascal": "p100", "volta": "v100", "turing": "t4",
        "ampere": "a100", "ada": "l4", "hopper": "h100", "blackwell": "b200",
    }
    labels = ", ".join(
        f"{arch.title()} {summary['architectures'].get(arch, 0)}" for arch in ARCHITECTURES
    )
    lines = [
        "<!-- GPU_CATALOG_START -->",
        f'        <div class="cat-total"><b>{len(profiles)}</b><span>profiles across '
        f'{len(summary["architectures"])} architectures and '
        f'{len(summary["compute_capabilities"])} compute capabilities</span></div>',
        f'        <div class="bar" role="img" aria-label="Profiles per architecture: {labels}">',
    ]
    for arch in ARCHITECTURES:
        count = summary["architectures"].get(arch, 0)
        noun = "profile" if count == 1 else "profiles"
        lines.append(
            f'          <span class="seg" data-arch="{arch}" style="flex-grow:{count}" '
            f'title="{arch.title()}: {count} {noun}"></span>'
        )
    lines.extend([
        "        </div>",
        '        <div class="bar-axis" aria-hidden="true"><span>Maxwell</span><span>→</span><span>Blackwell</span></div>',
        '        <div class="legend">',
    ])
    for arch in ARCHITECTURES:
        count = summary["architectures"].get(arch, 0)
        capabilities = sorted({p.compute_capability for p in profiles.values() if p.architecture == arch})
        capability_text = ", ".join(f"{major}.{minor}" for major, minor in capabilities)
        lines.append(
            f'          <div class="lg" data-arch="{arch}"><div class="lg-h"><i class="sw"></i>'
            f'{arch.title()}<span class="lg-n">{count}</span></div><div class="lg-cc">'
            f'CC {capability_text}</div><div class="lg-id">{samples[arch]}</div></div>'
        )
    lines.extend([
        "        </div>",
        '        <p class="cat-note">'
        f'{summary["segments"].get("consumer", 0)} consumer · '
        f'{summary["segments"].get("datacenter", 0)} data-center · '
        f'{summary["segments"].get("workstation", 0)} workstation · '
        f'{sum(count for segment, count in summary["segments"].items() if segment not in {"consumer", "datacenter", "workstation"})} embedded/test profiles</p>',
        "        <!-- GPU_CATALOG_END -->",
    ])
    rendered, replacements = re.subn(
        r"<!-- GPU_CATALOG_START -->.*?<!-- GPU_CATALOG_END -->",
        lambda _match: "\n".join(lines), source, flags=re.DOTALL,
    )
    if replacements != 1:
        raise ValueError("website must contain exactly one GPU_CATALOG section")
    return rendered


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the rendered inventory is stale.")
    args = parser.parse_args()
    rendered = render()
    website_source = WEBSITE.read_text(encoding="utf-8")
    website_rendered = render_website(website_source)
    if args.check:
        if (
            not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != rendered
            or website_source != website_rendered
        ):
            print("GPU inventory or website is stale; run python3 scripts/render_gpu_catalog.py")
            return 1
        print("GPU inventory and website match YAML profiles")
        return 0
    OUTPUT.write_text(rendered, encoding="utf-8")
    WEBSITE.write_text(website_rendered, encoding="utf-8")
    print(f"Wrote GPU inventory: {OUTPUT.relative_to(ROOT)}")
    print(f"Updated website: {WEBSITE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
